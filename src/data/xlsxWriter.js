const STYLE = { header: 1, date: 2, text: 3, wrap: 4 };

/**
 * sheet = { name, columns: [{ header, width, style?: 'date'|'text'|'wrap', list?: [...] }], rows: [[...]], freezeHeader }
 */
function sheetXml(sheet, dataRows = 1000) {
  const cols = sheet.columns.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width || 14}" customWidth="1"${c.style ? ` style="${STYLE[c.style]}"` : ''}/>`).join('');
  const cell = (v, r, c, style) => (typeof v === 'number' && Number.isFinite(v)
    ? `<c r="${colName(c)}${r}"${style ? ` s="${style}"` : ''}><v>${v}</v></c>`
    : `<c r="${colName(c)}${r}" t="inlineStr"${style ? ` s="${style}"` : ''}><is><t xml:space="preserve">${esc(v)}</t></is></c>`);
  const header = `<row r="1">${sheet.columns.map((c, i) => cell(c.header, 1, i, STYLE.header)).join('')}</row>`;
  const body = (sheet.rows || []).map((row, ri) => `<row r="${ri + 2}">${row.map((v, ci) => (v === '' || v == null ? '' : cell(v, ri + 2, ci, sheet.columns[ci]?.style ? STYLE[sheet.columns[ci].style] : 0))).join('')}</row>`).join('');
  const pane = sheet.freezeHeader ? '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>' : '<sheetViews><sheetView workbookViewId="0"/></sheetViews>';
  const lists = sheet.columns.map((c, i) => (c.list ? `<dataValidation type="list" allowBlank="1" showErrorMessage="0" sqref="${colName(i)}2:${colName(i)}${dataRows + 1}"><formula1>"${esc(c.list.join(','))}"</formula1></dataValidation>` : '')).filter(Boolean);
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${pane}<cols>${cols}</cols><sheetData>${header}${body}</sheetData>${lists.length ? `<dataValidations count="${lists.length}">${lists.join('')}</dataValidations>` : ''}</worksheet>`;
}

/** @param sheets [{ name, columns, rows, freezeHeader }] → Uint8Array (.xlsx) */
export function buildXlsx(sheets) {
  const files = [
    { name: '[Content_Types].xml', data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>${sheets.map((_, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join('')}</Types>` },
    { name: '_rels/.rels', data: '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>' },
    { name: 'xl/workbook.xml', data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>${sheets.map((s, i) => `<sheet name="${esc(s.name)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`).join('')}</sheets></workbook>` },
    { name: 'xl/_rels/workbook.xml.rels', data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${sheets.map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`).join('')}<Relationship Id="rId${sheets.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>` },
    { name: 'xl/styles.xml', data: STYLES },
    ...sheets.map((s, i) => ({ name: `xl/worksheets/sheet${i + 1}.xml`, data: sheetXml(s) })),
  ];
  return zip(files);
}

/** Բրաուզերում ֆայլի ներբեռնում */
export function downloadXlsx(fileName, bytes) {
  const url = URL.createObjectURL(new Blob([bytes], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }));
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
